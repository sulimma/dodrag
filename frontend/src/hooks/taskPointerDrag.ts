import { flushSync } from 'react-dom';

// Pointer input owns the gesture; existing task/date/sidebar handlers own its
// meaning. These local drag events are an adapter, not a native HTML/OLE drag.
export function installTaskPointerDrag() {
  let pending: { source: HTMLElement; pointerId: number; x: number; y: number } | null = null;
  let active = false;
  let x = 0, y = 0, alt = false, shift = false, frame = 0;
  let target: Element | null = null;
  let image: HTMLElement | null = null;
  let offsetX = 0, offsetY = 0;
  let suppressClick = false;
  const values = new Map<string, string>();
  const transfer = {
    effectAllowed: 'all', dropEffect: 'move',
    setData: (type: string, value: string) => values.set(type, value),
    getData: (type: string) => values.get(type) ?? '',
    setDragImage: (element: HTMLElement, dx: number, dy: number) => {
      image = element; offsetX = dx; offsetY = dy;
      Object.assign(element.style, { zIndex: '2147483647', opacity: '0.75' });
    },
  };
  const dispatch = (element: Element, type: string) => {
    const event = new MouseEvent(type, { bubbles: true, cancelable: true, clientX: x, clientY: y, altKey: alt, shiftKey: shift });
    Object.defineProperty(event, 'dataTransfer', { value: transfer });
    element.dispatchEvent(event);
    return event;
  };
  const resolveTarget = () => {
    if (!active) return;
    const next = document.elementFromPoint(x, y)?.closest('[data-task-drop-target]') ?? null;
    if (next !== target) {
      if (target) dispatch(target, 'dragleave');
      target = next;
    }
    if (target) dispatch(target, 'dragover');
    if (image) Object.assign(image.style, { left: `${x - offsetX}px`, top: `${y - offsetY}px` });
  };
  const tick = () => {
    // ponytail: one hit-test per frame only while dragging; also covers layout
    // animations and a stationary pointer without a separate layout observer.
    resolveTarget();
    if (active) frame = requestAnimationFrame(tick);
  };
  const finish = (drop: boolean) => {
    const source = pending?.source;
    if (active) {
      if (drop) { flushSync(resolveTarget); if (target) dispatch(target, 'drop'); }
      if (source) dispatch(source, 'dragend');
      suppressClick = true;
    }
    active = false; cancelAnimationFrame(frame);
    if (source && pending && source.hasPointerCapture?.(pending.pointerId)) source.releasePointerCapture(pending.pointerId);
    pending = null; target = null; image?.remove(); image = null; values.clear();
  };
  const down = (event: PointerEvent) => {
    // Only swallow the click generated by this drag's release, never a later click.
    suppressClick = false;
    if (event.button !== 0 || !event.isPrimary) return;
    const origin = event.target as Element;
    const source = origin.closest<HTMLElement>('[data-task-drag]');
    if (!source || source.hasAttribute('data-task-drag-disabled')) return;
    if (origin.closest('input,textarea,button,a,select,[contenteditable="true"],[data-task-selectable-text]')) return;
    // Bare card whitespace, IDs and the handle all start the same pointer gesture.
    finish(false); suppressClick = false;
    pending = { source, pointerId: event.pointerId, x: event.clientX, y: event.clientY };
    source.setPointerCapture?.(event.pointerId);
    event.preventDefault();
  };
  const move = (event: PointerEvent) => {
    if (!pending || event.pointerId !== pending.pointerId) return;
    x = event.clientX; y = event.clientY; alt = event.altKey; shift = event.shiftKey;
    if (!active && Math.hypot(x - pending.x, y - pending.y) >= 5) {
      let start!: MouseEvent;
      flushSync(() => { start = dispatch(pending!.source, 'dragstart'); });
      if (start.defaultPrevented) { finish(false); return; }
      active = true;
      frame = requestAnimationFrame(tick);
    }
    resolveTarget();
  };
  const up = (event: PointerEvent) => {
    if (!pending || event.pointerId !== pending.pointerId) return;
    x = event.clientX; y = event.clientY; alt = event.altKey; shift = event.shiftKey;
    finish(true);
  };
  const cancel = () => finish(false);
  const lostCapture = (event: PointerEvent) => {
    if (pending?.pointerId === event.pointerId) cancel();
  };
  const key = (event: KeyboardEvent) => {
    if (event.key === 'Escape') cancel();
    if (event.key === 'Alt') {
      alt = event.type === 'keydown';
      if (active) event.preventDefault(); // Do not activate the Windows/browser menu during a drag.
      resolveTarget();
    }
    if (event.key === 'Shift') { shift = event.type === 'keydown'; resolveTarget(); }
  };
  const nativeStart = (event: DragEvent) => {
    if (event.isTrusted && (event.target as Element).closest('[data-task-drag]')) event.preventDefault();
  };
  const click = (event: MouseEvent) => {
    if (suppressClick) { suppressClick = false; event.preventDefault(); event.stopImmediatePropagation(); }
  };
  window.addEventListener('pointerdown', down, true);
  window.addEventListener('pointermove', move, true);
  window.addEventListener('pointerup', up, true);
  window.addEventListener('pointercancel', cancel);
  window.addEventListener('lostpointercapture', lostCapture, true);
  window.addEventListener('blur', cancel);
  window.addEventListener('keydown', key, true);
  window.addEventListener('keyup', key, true);
  window.addEventListener('scroll', resolveTarget, true);
  window.addEventListener('resize', resolveTarget);
  window.addEventListener('dragstart', nativeStart, true);
  window.addEventListener('click', click, true);
  return () => {
    cancel();
    window.removeEventListener('pointerdown', down, true);
    window.removeEventListener('pointermove', move, true);
    window.removeEventListener('pointerup', up, true);
    window.removeEventListener('pointercancel', cancel);
    window.removeEventListener('lostpointercapture', lostCapture, true);
    window.removeEventListener('blur', cancel);
    window.removeEventListener('keydown', key, true);
    window.removeEventListener('keyup', key, true);
    window.removeEventListener('scroll', resolveTarget, true);
    window.removeEventListener('resize', resolveTarget);
    window.removeEventListener('dragstart', nativeStart, true);
    window.removeEventListener('click', click, true);
  };
}
